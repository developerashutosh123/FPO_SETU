#!/usr/bin/env node
// Copies the shared contract and design tokens into this project. Runs in predev/prebuild only when ../shared exists
// (on Vercel only the committed copies are present).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shared = join(root, '..', 'shared');
if (!existsSync(shared)) {
  console.log('sync-contract: ../shared not found, keeping the committed copies');
  process.exit(0);
}
const copies = [
  ['contract.ts', 'src/contract/contract.ts', '//'],
  ['design/tokens.css', 'src/styles/tokens.css', '/*'],
];
for (const [from, to, style] of copies) {
  const header = `Generated by scripts/sync-contract.mjs from shared/${from}. Generated, do not edit.`;
  const banner = style === '//' ? `// ${header}\n` : `/* ${header} */\n`;
  const out = join(root, to);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, banner + readFileSync(join(shared, from), 'utf8'));
  console.log(`sync-contract: ${from} -> ${to}`);
}
