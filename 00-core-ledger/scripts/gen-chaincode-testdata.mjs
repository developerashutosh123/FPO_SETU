// Generates chaincode/testdata/*.json with Node, using the SAME canonicalJson() that every portal signs with (shared/contract.ts).
// The Go tests verify these signatures, which proves the Go verifier and the TypeScript signer agree on bytes.
// Run: node --experimental-strip-types scripts/gen-chaincode-testdata.mjs
import { generateKeyPairSync, sign, createHash } from 'node:crypto';
import { writeFileSync, copyFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalJson } from '../../shared/contract.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'chaincode', 'testdata');
mkdirSync(out, { recursive: true });
copyFileSync(join(here, '..', '..', 'shared', 'testvectors', 'canonical-json.json'), join(out, 'canonical-json.json'));

const keys = (seed) => {
  const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
  const jwk = publicKey.export({ format: 'jwk' });
  const pubHex = '04' + Buffer.from(jwk.x, 'base64url').toString('hex') + Buffer.from(jwk.y, 'base64url').toString('hex');
  return { privateKey, pubHex };
};
const sig = (k, text) => sign('sha256', Buffer.from(text, 'utf8'), { key: k.privateKey, dsaEncoding: 'ieee-p1363' }).toString('hex');
const sha = (s) => createHash('sha256').update(s, 'utf8').digest('hex');

const farmer = keys();
const f2 = { sscc: '089012340000004517', farmerToken: 'FT-9c2e41a07b55d3f1', plotId: 'PL-7Q2M9X4K1A', commodity: 'POTATO', bagCount: 40, estWeightKg: 2000, harvestOrUnloadDate: '2026-11-02' };
const wbKey = keys(), qmKey = keys();
const wb = { deviceId: 'WB-CHG-01', grossKg: 3204, tareKg: 1240, netKg: 1964, at: '2026-11-04T10:15:00Z' };
const qm = { deviceId: 'QM-CHG-01', at: '2026-11-04T10:17:00Z', potato: { sizeGradeMm: '45-55', greeningPct: 0.8, rotPct: 0.4, cutsPct: 1.2 } };
const qmPaddy = { deviceId: 'QM-CHG-01', at: '2026-11-08T09:00:00Z', paddy: { moisturePct: 13.6, foreignMatterPct: 0.9, brokenPct: 3.2 } };
const bn = { sscc: '089012340000004517', farmerToken: 'FT-9c2e41a07b55d3f1', plotId: 'PL-7Q2M9X4K1A', commodity: 'POTATO', bagCount: 40, estWeightKg: 2000, harvestOrUnloadDate: '2026-11-02', note: 'আমি নিশ্চিত করছি' };

const vec = (name, key, obj) => { const canonical = canonicalJson(obj); return { name, publicKeyHex: key.pubHex, payload: obj, canonical, canonicalSha256: sha(canonical), signatureHex: sig(key, canonical) }; };
const data = {
  note: 'Generated by scripts/gen-chaincode-testdata.mjs with shared/contract.ts canonicalJson. Keys are throwaway test keys.',
  f2: vec('F2 lot commission payload', farmer, f2),
  f2Bengali: vec('F2 payload with Bengali text', farmer, bn),
  weighbridge: vec('F3 weighbridge reading', wbKey, wb),
  qualityPotato: vec('F3 quality reading, potato, decimals', qmKey, qm),
  qualityPaddy: vec('F3 quality reading, paddy, decimals', qmKey, qmPaddy),
};
writeFileSync(join(out, 'signatures.json'), JSON.stringify(data, null, 2) + '\n');
console.log('chaincode/testdata written:', Object.keys(data).filter((k) => k !== 'note').join(', '));
