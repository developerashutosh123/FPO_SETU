// Copies the shared contract into this project (contract.ts, the endpoint table, openapi.yaml). Run before dev and build.
// The copies carry a header and are never edited; test/contract-sync.test.ts fails if they drift from ../shared.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shared = join(root, '..', '..', 'shared');
if (!existsSync(shared)) { console.log('../shared not present (CI or deploy build): keeping the committed copies'); process.exit(0); }
mkdirSync(join(root, 'src', 'contract'), { recursive: true });
const copies = [
  ['contract.ts', 'contract.ts', '//'],
  ['mock/endpoints.mjs', 'endpoints.mjs', '//'],
  ['openapi.yaml', 'openapi.yaml', '#'],
];
for (const [from, to, c] of copies) {
  const body = readFileSync(join(shared, from), 'utf8');
  writeFileSync(join(root, 'src', 'contract', to), `${c} GENERATED by scripts/sync-contract.mjs from shared/${from}. Do not edit.\n${body}`);
}
// villages.json: the `villages` example of the shared fixture (GET /villages returns it)
const fx = JSON.parse(readFileSync(join(shared, 'fixtures', 'villages.json'), 'utf8'));
writeFileSync(join(root, 'src', 'contract', 'villages.json'), JSON.stringify(fx.examples.find((e) => e.endpoint === 'villages').body, null, 2) + '\n');
console.log('contract synced:', copies.map((c) => c[1]).join(', '));
