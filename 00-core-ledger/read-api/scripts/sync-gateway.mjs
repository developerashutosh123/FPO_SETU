// Copies the gateway's source (routes, services, db schema, contract copy) into src/gateway/. The read-only API serves the same
// routes with the same role filtering, so it must run the same code, not a re-implementation. The copies carry a header and are
// never edited; gateway/test/readapi-sync.test.ts fails if they drift. Run before dev and build.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gw = join(root, '..', 'gateway');
const out = join(root, 'src', 'gateway');
if (!existsSync(join(gw, 'src'))) { console.log('../gateway not present (deploy build): keeping the committed copies'); process.exit(0); }

/** Not copied: the live Fabric client, the indexer, the process entry points and the startup that needs a wallet. */
export const EXCLUDE = new Set(['index.ts', 'server.ts', 'fabric/client.ts', 'indexer/indexer.ts', 'services/startup.ts', 'docs.ts', 'contract/openapi.yaml']);

export function sourceFiles() {
  const files = [];
  const walk = (dir) => { for (const n of readdirSync(dir)) { const p = join(dir, n); if (statSync(p).isDirectory()) walk(p); else { const rel = relative(join(gw, 'src'), p).split('\\').join('/'); if (!EXCLUDE.has(rel)) files.push(rel); } } };
  walk(join(gw, 'src'));
  return files.sort();
}
export const HEADER = '// GENERATED by scripts/sync-gateway.mjs from gateway/src/. Do not edit.\n';
export const copyOf = (rel, body) => (rel.endsWith('.json') ? body : HEADER + body);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  rmSync(out, { recursive: true, force: true });
  for (const rel of sourceFiles()) {
    mkdirSync(dirname(join(out, rel)), { recursive: true });
    writeFileSync(join(out, rel), copyOf(rel, readFileSync(join(gw, 'src', rel), 'utf8')));
  }
  // the deduction and haircut rates the collateral and statement reads use
  writeFileSync(join(out, 'rates.json'), readFileSync(join(gw, 'config', 'rates.json'), 'utf8'));
  console.log(`gateway synced: ${sourceFiles().length} files`);
}
