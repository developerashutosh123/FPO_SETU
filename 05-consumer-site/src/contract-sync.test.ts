import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

// The committed copies must equal ../shared (contract section 11). Skipped where ../shared is absent, e.g. Vercel builds.
const shared = join(__dirname, '..', '..', 'shared');
const jobs = [
  { from: 'contract.ts', to: 'src/contract/contract.ts', header: '// generated by scripts/sync-contract.mjs from ../shared, do not edit\n' },
  { from: 'design/tokens.css', to: 'src/styles/tokens.css', header: '/* generated by scripts/sync-contract.mjs from ../shared, do not edit */\n' },
];
describe.skipIf(!existsSync(shared))('contract sync', () => {
  for (const j of jobs) {
    it(`${j.to} matches ../shared/${j.from}`, () => {
      expect(readFileSync(join(__dirname, '..', j.to), 'utf8')).toBe(j.header + readFileSync(join(shared, j.from), 'utf8'));
    });
  }
});
