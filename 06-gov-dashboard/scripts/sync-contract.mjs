// Copies the shared contract and design tokens into this project. On Vercel ../shared does not exist and the committed copies are used.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shared = join(root, '..', 'shared');
const JOBS = [
  { from: 'contract.ts', to: 'src/contract/contract.ts' },
  { from: 'design/tokens.css', to: 'src/styles/tokens.css' },
];
const header = (p) => (p.endsWith('.css') ? '/* generated by scripts/sync-contract.mjs from ../shared, do not edit */\n' : '// generated by scripts/sync-contract.mjs from ../shared, do not edit\n');

export function expected(job) {
  return header(job.to) + readFileSync(join(shared, job.from), 'utf8');
}

if (!existsSync(shared)) {
  console.log('sync-contract: ../shared not found, using the committed copies');
} else {
  for (const job of JOBS) {
    const dest = join(root, job.to);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, expected(job));
    console.log(`sync-contract: ${job.from} -> ${job.to}`);
  }
}
